  // Helper function to find which category an energetic pattern item belongs to
  static String getCategoryForPattern(String pattern) {
    for (var entry in energeticCategories.entries) {
      if (entry.value.contains(pattern)) {
        return entry.key;
      }
    }
    return 'Other Patterns';
  }

